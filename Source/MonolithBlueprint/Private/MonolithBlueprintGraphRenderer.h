#pragma once

#include "CoreMinimal.h"

class UBlueprint;
class UEdGraph;
class UEdGraphNode;
class UEdGraphPin;
class UEdGraphNode_Comment;

/**
 * Renders a Blueprint graph as compact pseudo-code (blueprint render_graph).
 *
 *   - Exec flow is walked from each entry (function entry first, then events by position), one
 *     statement per line. A node with several exec outputs (Branch, Sequence, Switch, loops)
 *     indents each linked output under its label.
 *   - A node reached by more than one exec link is labelled (L1: ...); later visits print
 *     "goto L1 (title)".
 *   - Pure nodes are inlined into the consuming argument (depth cap MaxExprDepth). Reroute knots
 *     are followed, split struct pins are folded back into their parent, and Break Struct,
 *     Get Array Item, Make Array/Map and enum literals render as X.Field, A[i], [...], {k: v},
 *     Enum::Value.
 *   - An impure node whose data outputs are used gets a handle (h1 = Call(...)), referenced as
 *     h1 or h1.Pin afterwards.
 *   - An argument appears only when its pin is linked or differs from its autogenerated default;
 *     hidden, self and WorldContextObject pins are left out when unlinked.
 *   - Comment boxes print as "# [text]" before the first statement they enclose; node comments as
 *     "// text"; boxes enclosing no statement are listed at the end of the graph.
 *   - Disabled nodes are tagged [DISABLED]; positions print as @(x,y) unless turned off.
 *   - Exec nodes no entry reaches are listed under "# not reachable from any entry (N exec node(s)):".
 *   - Graphs without exec flow (AnimGraph, transition rules, pure macros) render each sink as
 *     "Sink <- (Pin=expr, ...)".
 */
class FMonolithBlueprintGraphRenderer
{
public:
	struct FOptions
	{
		bool bPositions = true;
		int32 MaxExprDepth = 8;
	};

	/** The graphs render_graph covers when none are named, in a stable order (see .cpp). */
	static TArray<UEdGraph*> CollectGraphs(UBlueprint* Blueprint);

	/** "event_graph", "function", "macro", ... plus the header line for the graph. */
	static FString DescribeGraph(UBlueprint* Blueprint, UEdGraph* Graph, FString& OutType);

	/** Renders one graph, header included. */
	static FString RenderGraph(UBlueprint* Blueprint, UEdGraph* Graph, const FOptions& Options);
};
